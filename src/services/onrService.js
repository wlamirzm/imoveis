/**
 * Obtém estatísticas e dados de Registro de Imóveis ONR para um determinado bairro
 */
export function getDadosONR(bairroName) {
  const normBairro = bairroName || 'Brooklin';
  const info = ONR_CARTORIOS_ZONA_SUL[normBairro] || ONR_CARTORIOS_ZONA_SUL['Brooklin'];

  return {
    bairro: normBairro,
    ...info,
    linkMapaONR: `https://mapa.onr.org.br/?bairro=${encodeURIComponent(normBairro)}`,
    statusONR: 'Conectado ao SREI / Operador Nacional do Registro de Imóveis',
    dataConsulta: new Date().toLocaleDateString('pt-BR')
  };
}
